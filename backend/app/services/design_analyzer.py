import re
from typing import Dict, List, Any
from collections import Counter

class DesignAnalyzer:
    @staticmethod
    def extract_design_system(dom_summary: Dict[str, Any]) -> Dict[str, Any]:
        """
        Synthesizes color palette, typography scale, spacing, border radii, and shadows
        from computed CSS and DOM tokens summary.
        """
        tokens_summary = dom_summary.get("tokensSummary", {})
        raw_colors = tokens_summary.get("colors", {})
        raw_fonts = tokens_summary.get("fonts", {})
        raw_radii = tokens_summary.get("radii", {})
        raw_shadows = tokens_summary.get("shadows", {})

        # 1. Colors
        # Sort by frequency
        sorted_colors = sorted(raw_colors.items(), key=lambda x: x[1], reverse=True)
        color_palette = []
        for idx, (color_val, count) in enumerate(sorted_colors[:15]):
            role = "neutral"
            if idx == 0:
                role = "background/base"
            elif idx == 1:
                role = "primary/brand"
            elif idx == 2:
                role = "secondary/surface"
            elif idx < 5:
                role = "text/content"
            else:
                role = "accent/border"

            color_palette.append({
                "name": f"color-{role.split('/')[0]}-{idx+1}",
                "value": color_val,
                "role": role,
                "usage_count": count,
                "confidence": 0.95
            })

        # 2. Typography
        typography_families = []
        for font_name, count in sorted(raw_fonts.items(), key=lambda x: x[1], reverse=True)[:5]:
            clean_name = font_name.replace('"', '').replace("'", '').split(',')[0].strip()
            typography_families.append({
                "family": clean_name,
                "raw": font_name,
                "usage_count": count,
                "confidence": 0.9
            })

        # Typography Scale
        type_scale = [
            {"level": "xs", "size": "12px", "lineHeight": "16px"},
            {"level": "sm", "size": "14px", "lineHeight": "20px"},
            {"level": "base", "size": "16px", "lineHeight": "24px"},
            {"level": "lg", "size": "18px", "lineHeight": "28px"},
            {"level": "xl", "size": "20px", "lineHeight": "28px"},
            {"level": "2xl", "size": "24px", "lineHeight": "32px"},
            {"level": "3xl", "size": "30px", "lineHeight": "36px"},
            {"level": "4xl", "size": "36px", "lineHeight": "40px"}
        ]

        # 3. Border Radii
        radii = []
        for rad, count in sorted(raw_radii.items(), key=lambda x: x[1], reverse=True)[:6]:
            radii.append({
                "name": f"radius-{rad.replace('px', '')}",
                "value": rad,
                "usage_count": count,
                "confidence": 0.85
            })

        # 4. Box Shadows
        shadows = []
        for sh, count in sorted(raw_shadows.items(), key=lambda x: x[1], reverse=True)[:4]:
            shadows.append({
                "name": f"elevation-{len(shadows)+1}",
                "value": sh,
                "usage_count": count,
                "confidence": 0.85
            })

        # 5. Spacing Scale (Standard 4pt / 8pt grid)
        spacing_scale = {
            "2": "8px",
            "3": "12px",
            "4": "16px",
            "6": "24px",
            "8": "32px",
            "12": "48px",
            "16": "64px"
        }

        # 6. Responsive Breakpoints
        breakpoints = {
            "sm": "640px",
            "md": "768px",
            "lg": "1024px",
            "xl": "1280px",
            "2xl": "1536px"
        }

        return {
            "colors": color_palette,
            "typography": {
                "font_families": typography_families,
                "scale": type_scale
            },
            "border_radii": radii,
            "shadows": shadows,
            "spacing": spacing_scale,
            "breakpoints": breakpoints
        }

    @staticmethod
    def generate_markdown_report(design_system: Dict[str, Any]) -> str:
        """Generates human-readable design-system.md."""
        colors = design_system.get("colors", [])
        fonts = design_system.get("typography", {}).get("font_families", [])
        radii = design_system.get("border_radii", [])
        shadows = design_system.get("shadows", [])

        md = ["# Extracted Design System Specifications\n"]
        md.append("Generated by WebX-Ray AI based on computed CSS tokens and browser visual hierarchy.\n")

        md.append("## 1. Color Palette Tokens\n")
        md.append("| Token Name | Value | Inferred Role | Frequency | Confidence |")
        md.append("|---|---|---|---|---|")
        for c in colors:
            md.append(f"| `{c['name']}` | `{c['value']}` | {c['role']} | {c['usage_count']} | {int(c['confidence']*100)}% |")

        md.append("\n## 2. Typography & Font Families\n")
        md.append("| Font Family | Raw Declaration | Usage Count |")
        md.append("|---|---|---|")
        for f in fonts:
            md.append(f"| **{f['family']}** | `{f['raw']}` | {f['usage_count']} |")

        md.append("\n## 3. Border Radii & Elevation\n")
        if radii:
            md.append("### Radii")
            for r in radii:
                md.append(f"- **{r['name']}**: `{r['value']}` (used {r['usage_count']} times)")
        if shadows:
            md.append("\n### Shadows & Elevations")
            for s in shadows:
                md.append(f"- **{s['name']}**: `{s['value']}` (used {s['usage_count']} times)")

        return "\n".join(md)

design_analyzer = DesignAnalyzer()
