import os
import json
import zipfile
import shutil
from pathlib import Path
from typing import Dict, Any, List

from backend.app.config import settings
from backend.app.services.security import security_service

class ExportService:
    @staticmethod
    def create_zip_package(
        project_id: str,
        project_name: str,
        blueprint_data: Dict[str, Any],
        er_diagram: str = ""
    ) -> str:
        """
        Creates a structured, production-ready reconstruction package as a ZIP archive.
        Preserves the standardized WebX-Ray AI directory architecture.
        """
        export_root = settings.get_storage_path(project_id, "exports")
        temp_dir = export_root / f"bundle_{project_id[:8]}"
        
        # Clean previous temp if exists
        if temp_dir.exists():
            shutil.rmtree(temp_dir)

        # 1. Directory Tree
        (temp_dir / "analysis" / "pages").mkdir(parents=True, exist_ok=True)
        (temp_dir / "analysis" / "components").mkdir(parents=True, exist_ok=True)
        (temp_dir / "analysis" / "design").mkdir(parents=True, exist_ok=True)
        (temp_dir / "analysis" / "network").mkdir(parents=True, exist_ok=True)
        (temp_dir / "analysis" / "database").mkdir(parents=True, exist_ok=True)
        (temp_dir / "assets" / "screenshots").mkdir(parents=True, exist_ok=True)
        (temp_dir / "reports" / "visual").mkdir(parents=True, exist_ok=True)
        (temp_dir / "reports" / "functional").mkdir(parents=True, exist_ok=True)
        (temp_dir / "diagrams").mkdir(parents=True, exist_ok=True)
        (temp_dir / "ai-prompts").mkdir(parents=True, exist_ok=True)

        # 2. Write Root Files
        readme_content = f"""# {project_name} — WebX-Ray AI Reconstruction Package

This package contains complete technical specifications, component hierarchies, design tokens,
and AI coding agent prompts generated by WebX-Ray AI.

## Quick Start for Coding Agents
1. Start by reviewing `complete-blueprint.md`.
2. Inspect the prompt suited for your agent in `ai-prompts/`.
3. Follow the sequence in `implementation-roadmap.md`.
"""
        with open(temp_dir / "README.md", "w", encoding="utf-8") as f:
            f.write(readme_content)

        with open(temp_dir / "complete-blueprint.md", "w", encoding="utf-8") as f:
            f.write(security_service.sanitize_content(blueprint_data.get("complete_blueprint_md", "")))

        with open(temp_dir / "website-analysis.json", "w", encoding="utf-8") as f:
            json.dump(blueprint_data.get("website_analysis_json", {}), f, indent=2)

        with open(temp_dir / "reconstruction-master-prompt.md", "w", encoding="utf-8") as f:
            f.write(blueprint_data.get("reconstruction_master_prompt_md", ""))

        with open(temp_dir / "implementation-roadmap.md", "w", encoding="utf-8") as f:
            f.write(blueprint_data.get("implementation_roadmap_md", ""))

        with open(temp_dir / "testing-requirements.md", "w", encoding="utf-8") as f:
            f.write(blueprint_data.get("testing_requirements_md", ""))

        # 3. Write Analysis Subfiles
        with open(temp_dir / "analysis" / "pages" / "page-inventory.json", "w", encoding="utf-8") as f:
            json.dump(blueprint_data.get("page_inventory_json", []), f, indent=2)

        with open(temp_dir / "analysis" / "components" / "component-tree.json", "w", encoding="utf-8") as f:
            json.dump(blueprint_data.get("component_tree_json", []), f, indent=2)

        with open(temp_dir / "analysis" / "design" / "design-system.json", "w", encoding="utf-8") as f:
            json.dump(blueprint_data.get("design_system_json", {}), f, indent=2)

        with open(temp_dir / "analysis" / "network" / "api-contracts.json", "w", encoding="utf-8") as f:
            json.dump(blueprint_data.get("api_contracts_json", []), f, indent=2)

        # 4. Diagrams
        with open(temp_dir / "diagrams" / "database-er.mmd", "w", encoding="utf-8") as f:
            f.write(er_diagram or "erDiagram\n    SYSTEM ||--o{ LOGS : generates\n")

        # 5. AI Prompts
        with open(temp_dir / "ai-prompts" / "claude-code.md", "w", encoding="utf-8") as f:
            f.write(blueprint_data.get("claude_prompt_md", ""))

        with open(temp_dir / "ai-prompts" / "gemini.md", "w", encoding="utf-8") as f:
            f.write(blueprint_data.get("gemini_prompt_md", ""))

        with open(temp_dir / "ai-prompts" / "antigravity.md", "w", encoding="utf-8") as f:
            f.write(blueprint_data.get("antigravity_prompt_md", ""))

        with open(temp_dir / "ai-prompts" / "cursor.md", "w", encoding="utf-8") as f:
            f.write(blueprint_data.get("cursor_prompt_md", ""))

        with open(temp_dir / "ai-prompts" / "generic-agent.md", "w", encoding="utf-8") as f:
            f.write(blueprint_data.get("generic_prompt_md", ""))

        # 6. Copy available screenshots from project storage
        proj_screenshots = settings.STORAGE_DIR / project_id / "screenshots"
        if proj_screenshots.exists():
            for file in proj_screenshots.iterdir():
                if file.is_file() and file.suffix in (".png", ".jpg", ".webp"):
                    shutil.copy2(file, temp_dir / "assets" / "screenshots" / file.name)

        # 7. Zip the entire folder
        zip_filename = f"WebXRay-Reconstruction-{project_name.replace(' ', '_')}.zip"
        zip_path = export_root / zip_filename

        with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zipf:
            for root, _, files in os.walk(temp_dir):
                for file in files:
                    full_p = Path(root) / file
                    rel_p = full_p.relative_to(temp_dir)
                    zipf.write(full_p, rel_p)

        # Clean up temporary bundle directory
        shutil.rmtree(temp_dir)

        return str(zip_path)

export_service = ExportService()
